#!/bin/bash
# packgo-init.sh — 建立 PACK&GO 營運資料夾骨架(Mac 本機,非 repo)
#
# 起因(2026-08-06,Jeff):「太亂了,我現在的工作區域竟然不是流水線」。
# 一筆供應商付款當天走過十個地方,同一件事有三個家(Mac 資料夾 / SSD / admin),
# 所以每一步都要人腦去對。裁定:先以 Mac 資料夾為唯一事實來源。
#
# 用法:
#   bash scripts/packgo-init.sh              # 建在 ~/PACKGO
#   bash scripts/packgo-init.sh /其他/路徑
#
# 安全性:已存在的檔案一律不覆蓋(只補缺的),可重複執行。
# 只建立資料夾與 Markdown。不動既有資料、不碰網路、不碰資料庫。
#
# 本腳本刻意不含任何客人姓名或案件資料(2026-08-04 PII 慣例)。
# 建立個別案子請用 scripts/packgo-new-case.sh,姓名以參數帶入,不進 repo。

set -euo pipefail

ROOT="${1:-$HOME/PACKGO}"

created=0
skipped=0

write_if_absent() {
  local path="$1"
  if [ -e "$path" ]; then
    printf '  跳過(已存在) %s\n' "${path#"$ROOT"/}"
    skipped=$((skipped + 1))
    return 0
  fi
  mkdir -p "$(dirname "$path")"
  cat > "$path"
  printf '  建立 %s\n' "${path#"$ROOT"/}"
  created=$((created + 1))
}

echo "PACK&GO 營運資料夾 → $ROOT"
echo

# 狀態夾(流水線本體)
mkdir -p "$ROOT/01_詢價"
mkdir -p "$ROOT/02_報價中"
mkdir -p "$ROOT/03_待收訂金"
mkdir -p "$ROOT/04_已收訂_待下單"
mkdir -p "$ROOT/05_已下單_待供應商確認"
mkdir -p "$ROOT/06_已確認_待出發"
mkdir -p "$ROOT/07_已出發"
mkdir -p "$ROOT/08_已結案"
mkdir -p "$ROOT/09_取消作廢"

# 跨案子的長期資料
mkdir -p "$ROOT/_客人"
mkdir -p "$ROOT/_供應商"
mkdir -p "$ROOT/_範本"

echo "狀態夾與長期資料夾已就緒"
echo

write_if_absent "$ROOT/00_索引.md" <<'IDX'
# PACK&GO 營運索引

> 這個資料夾是營運的唯一事實來源。SSD 只是備份,不在那邊編輯。

## 怎麼用

案子放在狀態夾裡。往前推一步,就把整個案子資料夾拖到下一個狀態夾。
資料夾清單本身就是看板 —— 哪一夾堆積了,一眼看到卡在哪。

| 狀態夾 | 意思 | 推進條件 |
|---|---|---|
| `01_詢價` | 客人問了,還沒報價 | 報價寄出 → 02 |
| `02_報價中` | 報價已寄,等客人決定 | 客人說要 → 03 |
| `03_待收訂金` | 客人要了,等收錢 | 訂金入帳 → 04 |
| `04_已收訂_待下單` | 錢收了,還沒跟供應商下單 | 供應商下單完成 → 05 |
| `05_已下單_待供應商確認` | 已下單,等供應商確認(含付款憑證回傳) | 供應商確認 → 06 |
| `06_已確認_待出發` | 位子確定,等出發 | 出發日到 → 07 |
| `07_已出發` | 進行中 | 回來且結清 → 08 |
| `08_已結案` | 完成 | 不再動 |
| `09_取消作廢` | 取消 | 不再動 |

## 案子資料夾命名

`YYYY-MM-DD_產品代碼_客人`,日期在前才會照時間排。

## 案子資料夾內部(固定四層,不要自創)

```
00_案件.md      這個案子的唯一事實來源。要知道任何事,只開這一個檔
01_客人文件/    護照、簽證、客人給的資料
02_給客人/      報價單、收據、確認書、行程表
03_供應商/      供應商訂單、發票、付款憑證
04_通訊/        重要往來截圖、郵件備份
```

## 為什麼 02 和 03 要分開

紅線 2:供應商成本絕不能出現在給客人的文件上。

成本只存在 `03_供應商/`。`02_給客人/` 整夾直接寄出去都不會出事。
這是把「每次要記得檢查」變成「結構上不可能寄錯」。

## 長期資料

- `_客人/<客人>/` — 跨案子的長期資料:護照、偏好、歷史。案子會結束,人不會
- `_供應商/` — 供應商聯絡窗口、付款規矩、對帳
- `_範本/` — 新案子範本

## 開新案子

```
bash scripts/packgo-new-case.sh 01_詢價 2026-08-15 TW8 客人名字
```

或手動:

```
cp -R _範本/_案件範本 01_詢價/2026-08-15_TW8_客人名字
```

## 備份

整包複製到 SSD,不要在 SSD 上編輯。同一件事只能有一個家。
2026-08-06 的教訓:同一件事有三個家,就永遠不會是流水線。
IDX

